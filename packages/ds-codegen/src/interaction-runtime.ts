/** Shared Web DOM interaction law. Factories emit identical runtime source;
 * framework adapters retain their own reactive values, refs and event syntax. */
export const INTERACTION_RUNTIME_SOURCE = `// @generated by ds-codegen from interaction-runtime.ts.
export interface ActivationEvent {
  defaultPrevented: boolean;
  preventDefault(): void;
  currentTarget: EventTarget | null;
}

/** Consumer cancellation is observed before native default cancellation.
 * Native summary activation must be cancelled even for a disabled binding. */
export function canActivateInteraction(event: ActivationEvent, cancelNativeDefault = false): boolean {
  const cancelled = event.defaultPrevented;
  const host = event.currentTarget as HTMLElement | null;
  const disabled = host?.hasAttribute("disabled") || host?.getAttribute("aria-disabled") === "true";
  if (cancelNativeDefault) event.preventDefault();
  return !cancelled && !disabled;
}

export function toggleInteractionItem(value: string | string[], item: string, multiple: boolean, collapsible: boolean): string | string[] {
  if (multiple) {
    const current = Array.isArray(value) ? value : [];
    return current.includes(item) ? current.filter(entry => entry !== item) : [...current, item];
  }
  return value === item && collapsible ? "" : item;
}

/** Internal state is written only when the parent does not own the value. */
export function requestInteractionChange<T>(controlled: T | undefined, next: T, commit: (value: T) => void, notify?: (value: T) => void): void {
  if (controlled === undefined) commit(next);
  notify?.(next);
}

/** Native activation changes checked state before requesting a controlled value.
 * Restore the entire native group from the accepted value without changing focus. */
export function requestNativeRadioChange(event: { currentTarget: EventTarget | null }, request: () => void, readAccepted: () => string | undefined): void {
  const target = event.currentTarget as HTMLInputElement | null;
  if (!target || target.tagName?.toLowerCase() !== "input" || target.type !== "radio") {
    request();
    return;
  }
  const root = target.getRootNode() as Document | ShadowRoot | DocumentFragment;
  const peers = target.name
    ? Array.from(root.querySelectorAll<HTMLInputElement>('input[type="radio"]')).filter(radio => radio.name === target.name && radio.form === target.form)
    : [];
  if (!peers.includes(target)) peers.push(target);
  try {
    request();
  } finally {
    const accepted = readAccepted();
    for (const radio of peers) radio.checked = radio.value === accepted;
  }
}

/** Bind one behavior's events without replacing other bindings on the host.
 * The owner disposes this registration before replacing or unmounting it. */
export function bindInteractionEvents(host: HTMLElement, handlers: Record<string, ((event: Event) => void) | undefined>): () => void {
  const registered = Object.entries(handlers).flatMap(([name, handler]) => {
    if (!handler) return [];
    const listener = (event: Event) => { if (canActivateInteraction(event)) handler(event); };
    host.addEventListener(name, listener);
    return [[name, listener] as const];
  });
  return () => { for (const [name, listener] of registered) host.removeEventListener(name, listener); };
}
`;
